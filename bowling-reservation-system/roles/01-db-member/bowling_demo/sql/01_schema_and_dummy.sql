-- ==========================================
-- 1. 시퀀스 생성 (4개)
-- ==========================================
CREATE SEQUENCE SEQ_MEMBER_ID START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_LANE_ID START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_RESERVATION_ID START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_USAGE_ID START WITH 1 INCREMENT BY 1 NOCACHE;

-- ==========================================
-- 2. 테이블 생성 (5개 / ON DELETE CASCADE 미사용)
-- ==========================================
CREATE TABLE MEMBER (
    MEMBER_ID   NUMBER PRIMARY KEY,
    NAME        VARCHAR2(50) NOT NULL,
    PHONE       VARCHAR2(20) NOT NULL UNIQUE,
    EMAIL       VARCHAR2(100),
    GRADE       VARCHAR2(20) DEFAULT 'NORMAL' NOT NULL,
    CREATED_AT  DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE LANE (
    LANE_ID     NUMBER PRIMARY KEY,
    LANE_NO     NUMBER NOT NULL UNIQUE,
    STATUS      VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL
);

CREATE TABLE RESERVATION (
    RESERVATION_ID NUMBER PRIMARY KEY,
    MEMBER_ID      NUMBER NOT NULL,
    RES_DATE       DATE NOT NULL,
    STATUS         VARCHAR2(20) DEFAULT 'RESERVED' NOT NULL,
    CREATED_AT     DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_RES_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER(MEMBER_ID)
);

CREATE TABLE RESERVATION_LANE (
    RESERVATION_ID NUMBER NOT NULL,
    LANE_ID        NUMBER NOT NULL,
    CONSTRAINT PK_RES_LANE PRIMARY KEY (RESERVATION_ID, LANE_ID),
    CONSTRAINT FK_RL_RES FOREIGN KEY (RESERVATION_ID) REFERENCES RESERVATION(RESERVATION_ID),
    CONSTRAINT FK_RL_LANE FOREIGN KEY (LANE_ID) REFERENCES LANE(LANE_ID)
);

CREATE TABLE USAGE (
    USAGE_ID       NUMBER PRIMARY KEY,
    RESERVATION_ID NUMBER NOT NULL,
    START_TIME     DATE,
    END_TIME       DATE,
    TOTAL_FEE      NUMBER DEFAULT 0,
    CONSTRAINT FK_USAGE_RES FOREIGN KEY (RESERVATION_ID) REFERENCES RESERVATION(RESERVATION_ID)
);

