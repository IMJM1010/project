CREATE TABLE MEMBER (
 member_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 login_id VARCHAR2(50 CHAR) NOT NULL UNIQUE, password_hash VARCHAR2(255 CHAR) NOT NULL,
 member_name VARCHAR2(50 CHAR) NOT NULL, phone_number VARCHAR2(20 CHAR) NOT NULL UNIQUE,
 email VARCHAR2(254 CHAR), role VARCHAR2(10 CHAR) DEFAULT 'MEMBER' NOT NULL CHECK(role IN ('MEMBER','ADMIN')),
 status VARCHAR2(10 CHAR) DEFAULT 'ACTIVE' NOT NULL CHECK(status IN ('ACTIVE','INACTIVE')),
 no_show_count NUMBER(5) DEFAULT 0 NOT NULL CHECK(no_show_count>=0), reservation_block_until TIMESTAMP(6),
 created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL, updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL, deactivated_at TIMESTAMP(6)
);
CREATE TABLE LANE (
 lane_id NUMBER(10) PRIMARY KEY, lane_number NUMBER(2) NOT NULL UNIQUE CHECK(lane_number BETWEEN 1 AND 10),
 status VARCHAR2(15 CHAR) DEFAULT 'AVAILABLE' NOT NULL CHECK(status IN ('AVAILABLE','IN_USE','MAINTENANCE')),
 updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE RESERVATION (
 reservation_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, member_id NUMBER(10) NOT NULL REFERENCES MEMBER(member_id),
 reservation_start_time TIMESTAMP(6) NOT NULL, reservation_end_time TIMESTAMP(6) NOT NULL,
 person_count NUMBER(3) NOT NULL CHECK(person_count BETWEEN 1 AND 40), actual_person_count NUMBER(3) CHECK(actual_person_count>=0),
 status VARCHAR2(25 CHAR) DEFAULT 'CONFIRMED' NOT NULL CHECK(status IN ('CONFIRMED','IN_USE','COMPLETED','CANCELLED','NO_SHOW','REALLOCATION_FAILED')),
 cancelled_at TIMESTAMP(6), cancel_reason VARCHAR2(30 CHAR) CHECK(cancel_reason IN ('MEMBER_REQUEST','LANE_FAILURE','ADMIN_OTHER')), no_show_processed_at TIMESTAMP(6),
 created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL, updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT CK_RESERVATION_TIME CHECK(reservation_end_time>reservation_start_time)
);
CREATE TABLE RESERVATION_LANE (
 reservation_lane_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reservation_id NUMBER(10) NOT NULL REFERENCES RESERVATION(reservation_id), lane_id NUMBER(10) NOT NULL REFERENCES LANE(lane_id),
 assigned_start_time TIMESTAMP(6) NOT NULL, usage_status VARCHAR2(15 CHAR) DEFAULT 'WAITING' NOT NULL CHECK(usage_status IN ('WAITING','IN_USE','COMPLETED','UNUSED')),
 CONSTRAINT UK_RL_RES_LANE UNIQUE(reservation_id,lane_id)
);
CREATE TABLE USAGE (
 usage_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reservation_lane_id NUMBER(10) NOT NULL UNIQUE REFERENCES RESERVATION_LANE(reservation_lane_id),
 actual_start_time TIMESTAMP(6) NOT NULL, actual_end_time TIMESTAMP(6),
 CONSTRAINT CK_USAGE_TIME CHECK(actual_end_time IS NULL OR actual_end_time>=actual_start_time)
);
CREATE INDEX IX_RES_MEMBER_TIME ON RESERVATION(member_id,reservation_start_time,reservation_end_time);
CREATE INDEX IX_RL_LANE_TIME ON RESERVATION_LANE(lane_id,assigned_start_time);
CREATE INDEX IX_RES_STATUS_TIME ON RESERVATION(status,reservation_start_time);
