CREATE TABLE MEMBER (
 member_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
 login_id VARCHAR2(50 CHAR) NOT NULL,
 password_hash VARCHAR2(255 CHAR) NOT NULL,
