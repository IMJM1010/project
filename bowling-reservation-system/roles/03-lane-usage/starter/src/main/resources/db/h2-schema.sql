-- Isolated H2 schema; matches named constraints of the Oracle ERD. H2 uses VARCHAR2 without Oracle CHAR length syntax.
CREATE TABLE MEMBER (
 member_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
 login_id VARCHAR2(50) NOT NULL,
 password_hash VARCHAR2(255) NOT NULL,
 member_name VARCHAR2(50) NOT NULL,
 phone_number VARCHAR2(20) NOT NULL,
 email VARCHAR2(254),
 role VARCHAR2(10) DEFAULT 'MEMBER' NOT NULL,
 status VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
 no_show_count NUMBER(5) DEFAULT 0 NOT NULL,
 reservation_block_until TIMESTAMP(6),
 created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
 deactivated_at TIMESTAMP(6),
 CONSTRAINT PK_MEMBER PRIMARY KEY(member_id),
 CONSTRAINT UK_MEMBER_LOGIN_ID UNIQUE(login_id),
 CONSTRAINT UK_MEMBER_PHONE UNIQUE(phone_number),
 CONSTRAINT CK_MEMBER_ROLE CHECK(role IN ('MEMBER','ADMIN')),
 CONSTRAINT CK_MEMBER_STATUS CHECK(status IN ('ACTIVE','INACTIVE')),
 CONSTRAINT CK_MEMBER_NO_SHOW CHECK(no_show_count>=0)
);
CREATE TABLE LANE (
 lane_id NUMBER(10),
 lane_number NUMBER(2) NOT NULL,
 status VARCHAR2(15) DEFAULT 'AVAILABLE' NOT NULL,
 updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT PK_LANE PRIMARY KEY(lane_id),
 CONSTRAINT UK_LANE_NUMBER UNIQUE(lane_number),
 CONSTRAINT CK_LANE_NUMBER CHECK(lane_number BETWEEN 1 AND 10),
 CONSTRAINT CK_LANE_STATUS CHECK(status IN ('AVAILABLE','IN_USE','MAINTENANCE'))
);
CREATE TABLE RESERVATION (
 reservation_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
 member_id NUMBER(10) NOT NULL,
 reservation_start_time TIMESTAMP(6) NOT NULL,
 reservation_end_time TIMESTAMP(6) NOT NULL,
 person_count NUMBER(3) NOT NULL,
 actual_person_count NUMBER(3),
 status VARCHAR2(25) DEFAULT 'CONFIRMED' NOT NULL,
 cancelled_at TIMESTAMP(6),
 cancel_reason VARCHAR2(30),
 no_show_processed_at TIMESTAMP(6),
 created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT PK_RESERVATION PRIMARY KEY(reservation_id),
 CONSTRAINT FK_RESERVATION_MEMBER FOREIGN KEY(member_id) REFERENCES MEMBER(member_id),
 CONSTRAINT CK_RESERVATION_TIME CHECK(reservation_end_time>reservation_start_time),
 CONSTRAINT CK_RESERVATION_PERSON CHECK(person_count BETWEEN 1 AND 40),
 CONSTRAINT CK_RESERVATION_ACTUAL CHECK(actual_person_count>=0),
 CONSTRAINT CK_RESERVATION_STATUS CHECK(status IN ('CONFIRMED','IN_USE','COMPLETED','CANCELLED','NO_SHOW','REALLOCATION_FAILED')),
 CONSTRAINT CK_RESERVATION_CANCEL CHECK(cancel_reason IN ('MEMBER_REQUEST','LANE_FAILURE','ADMIN_OTHER'))
);
CREATE TABLE RESERVATION_LANE (
 reservation_lane_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
 reservation_id NUMBER(10) NOT NULL,
 lane_id NUMBER(10) NOT NULL,
 assigned_start_time TIMESTAMP(6) NOT NULL,
 usage_status VARCHAR2(15) DEFAULT 'WAITING' NOT NULL,
 CONSTRAINT PK_RESERVATION_LANE PRIMARY KEY(reservation_lane_id),
 CONSTRAINT FK_RL_RESERVATION FOREIGN KEY(reservation_id) REFERENCES RESERVATION(reservation_id),
 CONSTRAINT FK_RL_LANE FOREIGN KEY(lane_id) REFERENCES LANE(lane_id),
 CONSTRAINT UK_RL_RES_LANE UNIQUE(reservation_id,lane_id),
 CONSTRAINT CK_RL_USAGE_STATUS CHECK(usage_status IN ('WAITING','IN_USE','COMPLETED','UNUSED'))
);
CREATE TABLE USAGE (
 usage_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
 reservation_lane_id NUMBER(10) NOT NULL,
 actual_start_time TIMESTAMP(6) NOT NULL,
 actual_end_time TIMESTAMP(6),
 CONSTRAINT PK_USAGE PRIMARY KEY(usage_id),
 CONSTRAINT FK_USAGE_RL FOREIGN KEY(reservation_lane_id) REFERENCES RESERVATION_LANE(reservation_lane_id),
 CONSTRAINT UK_USAGE_RL UNIQUE(reservation_lane_id),
 CONSTRAINT CK_USAGE_TIME CHECK(actual_end_time IS NULL OR actual_end_time>=actual_start_time)
);
CREATE INDEX IX_RES_MEMBER_TIME ON RESERVATION(member_id,reservation_start_time,reservation_end_time);
CREATE INDEX IX_RL_LANE_TIME ON RESERVATION_LANE(lane_id,assigned_start_time);
CREATE INDEX IX_RES_STATUS_TIME ON RESERVATION(status,reservation_start_time);
